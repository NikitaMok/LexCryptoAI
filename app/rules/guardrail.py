"""Запрет на выдачу способов обхода закона.

Часть 2 статьи 30 № 282-ФЗ запрещает информировать резидентов о способах
совершения сделок с цифровыми валютами в нарушение закона и предоставлять для
этого программное обеспечение. Сервис — это программное обеспечение,
консультирующее резидентов по таким сделкам, поэтому ограничение относится
к нему напрямую.

Отсюда правило: система выдаёт только приведение договора в соответствие. Ни при
какой формулировке запроса она не должна предлагать дробление платежей ради ухода
из-под порога, сокрытие предмета договора или иной обход требования. Если сделка
в предложенной конструкции недопустима, об этом сообщается прямо.

Модуль проверяет исходящий текст. Сейчас все тексты заключения авторские
и проходят проверку по определению; смысл в том, чтобы ни один будущий текст
от языковой модели не попал к пользователю в обход этой проверки.

Проверка описывает *советы*, а не *описания нарушений*: правило THR-003 обязано
называть признаки искусственного дробления платежей, и это законная
формулировка. Запрещены побудительные конструкции.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# (шаблон, чем именно формулировка опасна)
_FORBIDDEN: tuple[tuple[str, str], ...] = (
    (r"чтобы\s+(?:банк|контролёр|Росфинмониторинг|налоговая|ЦБ)\w*\s+не\s+\w+",
     "совет скрыть операцию от контролирующего лица"),
    (r"чтобы\s+не\s+(?:превыс|подпада|привлека|попада)\w+",
     "совет обойти порог или основание контроля"),
    (r"(?:раздроб|разбей|разбить|раздели)\w*\s+(?:платеж|платёж|сумм|оплат)\w*",
     "совет раздробить платёж"),
    (r"обойти\s+(?:требовани|контрол|порог|норм|запрет|ограничени)\w*",
     "прямое предложение обойти требование"),
    (r"(?:избежать|избегать)\s+(?:обязательного\s+контроля|постановки\s+на\s+учёт|"
     r"валютного\s+контроля|блокировк\w+)",
     "совет уклониться от контрольной процедуры"),
    (r"не\s+указыв\w+\s+(?:в\s+договоре|сумму|назначение|предмет|цифровую\s+валюту)",
     "совет умолчать о существенном условии"),
    (r"(?:замаскир|скрыть|утаить|сокрыть)\w*\s+(?:предмет|назначение|сумму|"
     r"расчёты|операци|характер)\w*",
     "совет скрыть существо сделки"),
    (r"фиктивн\w+\s+(?:договор|услуг|поставк|основани|сделк)\w*",
     "предложение оформить фиктивное основание"),
    (r"(?:заниз|завыс)\w+\s+(?:сумму|стоимость|цену)",
     "совет исказить цену договора"),
    (r"формально\s+(?:соблюсти|выполнить|подойти|отчитаться)",
     "совет соблюсти требование формально, без исполнения по существу"),
    (r"(?:серая|серую|серой)\s+(?:схем|зон)\w*",
     "предложение работать вне правового режима"),
    (r"без\s+постановки\s+на\s+учёт",
     "совет провести операцию без обязательной регистрации"),
)

_COMPILED = tuple((re.compile(pattern, re.IGNORECASE), reason) for pattern, reason in _FORBIDDEN)


class CircumventionAttempt(RuntimeError):
    """Текст, который нельзя показывать пользователю."""


@dataclass(frozen=True)
class GuardrailFinding:
    fragment: str
    reason: str
    context: str = ""

    def __str__(self) -> str:
        where = f" ({self.context})" if self.context else ""
        return f"«{self.fragment}» — {self.reason}{where}"


def inspect(text: str, context: str = "") -> list[GuardrailFinding]:
    if not text:
        return []

    normalized = " ".join(text.split())
    return [
        GuardrailFinding(fragment=match.group(0), reason=reason, context=context)
        for regex, reason in _COMPILED
        for match in regex.finditer(normalized)
    ]


def assert_clean(text: str, context: str = "") -> None:
    findings = inspect(text, context)
    if findings:
        raise CircumventionAttempt(
            "текст содержит совет обойти требование закона: "
            + "; ".join(str(finding) for finding in findings)
        )


def verify_report(report) -> list[GuardrailFinding]:  # noqa: ANN001 — избегаем циклического импорта
    """Проверяет каждый текст, попадающий в заключение."""
    findings: list[GuardrailFinding] = []

    for finding in report.findings:
        for field_name in ("title", "evidence", "sanction"):
            findings.extend(
                inspect(getattr(finding, field_name, "") or "", f"{finding.code}.{field_name}")
            )

    return findings
